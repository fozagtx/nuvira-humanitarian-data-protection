function sslOption() {
  const caPath = `${homedir()}/.postgresql/root.crt`;
  if (existsSync(caPath)) {
    return { rejectUnauthorized: true, ca: readFileSync(caPath).toString() };
  }
  return "require" as const;
}

async function ensureSchema(sql: ReturnType<typeof postgres>) {
  if (_schemaReady) return;
  for (const statement of TABLE_DDL) {
    await sql.unsafe(statement);
  }
  _schemaReady = true;
}

export async function getDb() {
  if (_db) return _db;
  const url = process.env.DATABASE_URL;
  if (!url || !url.startsWith("postgres")) {
    if (url) console.warn("[Database] DATABASE_URL must be a postgres:// or postgresql:// CockroachDB connection string");
    return null;
  }
  try {
    _sql = postgres(url, { ssl: sslOption(), max: 4, idle_timeout: 20, connect_timeout: 15, onnotice: () => {} });
    await _sql`SELECT 1`;
    await ensureSchema(_sql);
    _db = drizzle(_sql);
    console.log("[Database] Connected to CockroachDB");
  } catch (error) {
    console.warn("[Database] Failed to connect:", error instanceof Error ? error.message : error);
    await _sql?.end({ timeout: 0 }).catch(() => undefined);
    _sql = null;
    _db = null;
  }
  return _db;
}

export function sha256(value: string) { return createHash("sha256").update(value).digest("hex"); }
export function computeEventHash(previousHash: string, eventType: string, findingId: number | undefined, assetId: number | undefined, payload: string) { return sha256([previousHash, eventType, findingId ?? '', assetId ?? '', payload].join('|')); }
export function requireApprovedAction(approved: boolean) { if (!approved) throw new Error('Approval required before destructive action'); }

export async function upsertUser(user: InsertUser): Promise<void> {
  if (!user.openId) throw new Error("User openId is required for upsert");
  const db = await getDb(); if (!db) return;
  const values: InsertUser = { openId: user.openId };
  const updateSet: Record<string, unknown> = {};
  (['name', 'email', 'loginMethod'] as const).forEach(field => { if (user[field] !== undefined) { values[field] = user[field] ?? null; updateSet[field] = values[field]; } });
  values.lastSignedIn = user.lastSignedIn ?? new Date(); updateSet.lastSignedIn = values.lastSignedIn;
  if (user.role) { values.role = user.role; updateSet.role = user.role; }
  else if (user.openId === ENV.ownerOpenId) { values.role = 'admin'; updateSet.role = 'admin'; }
  await db.insert(users).values(values).onConflictDoUpdate({ target: users.openId, set: updateSet });
}

export async function getUserByOpenId(openId: string) {
  const db = await getDb(); if (!db) return undefined;
  const result = await db.select().from(users).where(eq(users.openId, openId)).limit(1); return result[0];
}

