type MemoryApproval = { id: number; findingId: number; decision: "approved" | "rejected"; action: "redact" | "revoke_access"; note: string | null; approvedBy: number | null; createdAt: Date };
type MemoryLink = { id: number; findingId: number; policyId: number; relevance: number };

const memory = {
  nextId: 1,
  policies: [] as PolicyDocument[],
  assets: [] as DataAsset[],
  findings: [] as Finding[],
  links: [] as MemoryLink[],
  approvals: [] as MemoryApproval[],
  events: [] as AgentEvent[],
};

function nextId() { return memory.nextId++; }
function now() { return new Date(); }

function dashboardFrom(store: { assets: DataAsset[]; findings: Finding[]; approvals: MemoryApproval[]; events: AgentEvent[]; policies: PolicyDocument[]; links: MemoryLink[] }) {
  const assetMap = new Map(store.assets.map(asset => [asset.id, asset]));
  const enrichedFindings = [...store.findings].sort((a, b) => b.createdAt.getTime() - a.createdAt.getTime()).map(finding => ({ ...finding, source: assetMap.get(finding.assetId)?.source ?? "OneDrive", assetName: assetMap.get(finding.assetId)?.name ?? "Unknown asset" }));
  const policyMap = Object.fromEntries(store.findings.map(finding => [finding.id, store.links.filter(link => link.findingId === finding.id).map(link => store.policies.find(policy => policy.id === link.policyId)).filter(Boolean)]));
  return {
    assets: [...store.assets].sort((a, b) => b.createdAt.getTime() - a.createdAt.getTime()),
    findings: enrichedFindings,
    approvals: [...store.approvals].sort((a, b) => b.createdAt.getTime() - a.createdAt.getTime()),
    events: [...store.events].sort((a, b) => b.createdAt.getTime() - a.createdAt.getTime()).slice(0, 80),
    policies: store.policies,
    policyMap,
  };
}

